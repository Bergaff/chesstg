/**
 * Язык реплик бота.
 *
 * Его никто не выбирает вручную: берётся `language_code` из того сообщения
 * Telegram, на которое бот отвечает. Так приветствие, справка и подтверждение
 * привязки приезжают на языке клиента, а не на языке разработчика, и никакого
 * переключателя в боте не появляется.
 *
 * Экраны игры переводятся на клиенте (src/lib/i18n.ts) - там словарь по русским
 * строкам. Реплик бота мало, они длинные и сильно различаются порядком слов,
 * поэтому здесь перевод лежит рядом с русским текстом: `lang === 'en' ? ... : ...`
 * читается без словаря, и пропустить ветку в таком месте нельзя физически.
 *
 * Уведомление пригласившему (notifyReferrer) остаётся русским: у приглашающей
 * сети язык в базе не хранится, а заводить колонку ради одной фразы - значит
 * требовать миграцию там, где её никто не ждёт.
 */

export type BotLang = 'ru' | 'en';

/** Всё, что не `ru*`, говорит по-английски - то же правило, что и в клиенте. */
export function botLang(languageCode: unknown): BotLang {
  return typeof languageCode === 'string' && languageCode.toLowerCase().startsWith('ru') ? 'ru' : 'en';
}

/** Короткая подпись: кнопка, ответ на нажатие, заголовок. */
export function pick(lang: BotLang, ru: string, en: string): string {
  return lang === 'en' ? en : ru;
}
