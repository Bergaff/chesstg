// «Гонки»: король против фигур, которые приходят сверху по бегущему полю.
//
// Игрок - король: один шаг в любую из восьми сторон, взятие так же и назад
// включительно. Фигуры рождаются в верхних рядах, а после каждого хода короля
// всё поле уезжает на ряд вниз. Нижний ряд сходит с поля и уносит всё, что на
// нём стояло, включая короля: за доску он не держится. Значит каждый ход надо
// подниматься, шаг в сторону или назад стоит ряда, а долгое стояние в самом низу
// кончается проигрышем. Отсюда и «король двигается, но остаётся на втором ряду»:
// он остаётся, пока ходит вверх.
//
// Нарастает ширина поля. Старт - три колонки при восьми рядах, то есть ровно
// половина шахматного ряда, и каждые RACE_FIGURES_PER_COLUMN пришедших фигур
// справа добавляется колонка, пока поле не станет всей доской. Приток занимает
// всё поле, поэтому рост ширины и есть местная сложность: считать приходится по
// всё большему числу линий.
//
// Финиша нет: забег кончается, когда короля поймали, когда нижний ряд унёс его
// с поля, или когда ходить стало некуда. Счёт это пережитые ходы, поэтому рекорд
// и уровень режима считаются с одного числа: каждые RACE_MOVES_PER_LEVEL ходов
// режим поднимает уровень. Уровень не влияет на поле: все играют на одном, иначе
// рекорды были бы несопоставимы.
//
// Здесь только таблица напряжённости. Правила живут в `modes.ts`
// (`player: 'king'`, `motion: 'greedy'`, `goal: 'survive'`, `scroll: true`),
// приток и сдвиг ряда - в `rules.ts`.

import type { PieceType } from './types';

/** Предел роста поля: вся доска. Шире восьми колонок забег не становится. */
export const RACE_WIDTH = 8;
/** С чем поле стартует: три колонки, половина шахматного ряда. */
export const RACE_MIN_WIDTH = 3;
/**
 * Рядов столько же, сколько в шахматной доске. При сдвиге каждый ход это восемь
 * ходов жизни фигуры от линии рождения до края - ровно тот запас, за который
 * игрок успевает её прочитать.
 */
export const RACE_ROWS = 8;
/** Стартовый ряд короля: второй от низа, один ряд под ним остаётся. */
export const RACE_KING_ROW = 1;
/** Сколько фигур стоит на поле до первого хода - это потолок, а не факт. */
export const RACE_PREFILL = 3;
/**
 * Сколько фигур реально стоит на старте: на трёх колонках три фигуры это стена
 * из шести клеток верхних рядов, и королю некуда идти. Поэтому пробка держится
 * от ширины: узкое поле получает одного наблюдателя, широкое - полную норму.
 */
export function racePrefillFor(width: number): number {
  return Math.max(1, Math.min(RACE_PREFILL, width - 2));
}
/** Приток занимает столько верхних рядов: в один ряд фигуры встали бы стеной. */
export const RACE_SPAWN_ROWS = 2;
/**
 * Сколько новых фигур должно прийти, чтобы справа добавился колонка. Пять: при
 * притоке раз в два-три хода это около десятка ходов игры, то есть колонка
 * вырастает на глазах, но не каждые два хода.
 */
export const RACE_FIGURES_PER_COLUMN = 5;
/**
 * Сколько пережитых ходов поднимает уровень режима. Число по замеру жадного бота
 * на этом же правиле: один забег должен давать два-три уровня, а не один и не
 * десять.
 */
export const RACE_MOVES_PER_LEVEL = 12;
/**
 * Сколько пережитых ходов поднимает ВОЛНУ: частоту притока и состав пула. От
 * уровня режима она отделена, потому что уровень ждёт рекорда, а волна обязана
 * менять игру здесь же. Ширина поля от волны не зависит: она растёт по числу
 * пришедших фигур, иначе рост зависел бы от того, как долго ты продержался.
 */
export const RACE_TIER_MOVES = 8;

/**
 * Сколько колонок в поле после того, как пришло `spawned` фигур: старт с трёх,
 * дальше одна колонка справа каждые RACE_FIGURES_PER_COLUMN, предел - вся доска.
 * Колонки добавляются справа, поэтому левый край за весь забег не двигается.
 */
export function raceWidthForSpawned(spawned: number): number {
  const extra = Math.floor(Math.max(0, spawned) / RACE_FIGURES_PER_COLUMN);
  return Math.min(RACE_WIDTH, RACE_MIN_WIDTH + extra);
}

/** Сколько фигур приходит за такт на данном напряжении. */
export function raceSpawnPerTurn(tier: number): number {
  return tier <= 2 ? 1 : tier <= 5 ? 2 : 3;
}

/**
 * Раз в сколько ходов приходит волна. Первая идёт заметно реже: забег не должен
 * обрываться раньше, чем игрок понял, что ряды уезжают вниз каждый ход и что за
 * них надо подниматься.
 */
export function raceSpawnEvery(tier: number): number {
  return tier <= 1 ? 3 : tier <= 3 ? 2 : 1;
}

/** Уровень режима по счёту забега: счёт и есть пережитые ходы. */
export function raceLevelForMoves(moves: number): number {
  return 1 + Math.floor(Math.max(0, moves) / RACE_MOVES_PER_LEVEL);
}

/**
 * Волна по пережитым ходам: по ней считаются частота притока и его состав.
 * Полоса притока при этом не сужается: фигуры занимают всё поле, ширина которого
 * растёт своим счётом.
 */
export function raceTierForMoves(moves: number): number {
  return 1 + Math.floor(Math.max(0, moves) / RACE_TIER_MOVES);
}

/**
 * Кем пополняется поле. Пешек здесь нет намеренно: они идут по одному ряду и
 * сходят с поля раньше, чем дойдут до короля, то есть только занимают клетки.
 * Конь и слон создают уклонения, ладья и ферзь прижимают линию.
 */
export function raceSpawnPool(tier: number): PieceType[] {
  if (tier <= 1) return ['rook', 'bishop', 'knight'];
  if (tier <= 3) return ['rook', 'rook', 'bishop', 'knight', 'knight'];
  if (tier <= 6) return ['rook', 'bishop', 'knight', 'knight', 'queen'];
  return ['rook', 'rook', 'bishop', 'knight', 'knight', 'queen', 'queen'];
}

/** Награда за забег: платим за дистанцию, потому что победы в режиме нет. */
export function raceCoinReward(moves: number): number {
  const level = raceLevelForMoves(moves);
  return Math.min(50, 5 + level + Math.floor(moves / 4));
}
