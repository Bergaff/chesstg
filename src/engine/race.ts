// «Гонки»: король против фигур, которые приходят сверху по бегущему полю.
//
// Игрок - король: один шаг в любую из восьми сторон, взятие так же и назад
// включительно. Фигуры рождаются в верхних рядах, поле течёт вниз: на такт
// нижний ряд уходит за край и уносит всё, что на нём стояло, а сверху приходит
// новый. Короля сдвиг не трогает: он стоит на своём втором ряду, «двигается, но
// остаётся», а ряды протекают мимо него.
//
// Нарастает не поле и не уровень, а ширина притока: сначала фигуры встают в
// три колонки по центру, и фланги свободны, к шестой волне занят весь фронт.
// Плюс к такту поля и к составу пула (`raceSpawnPool`) это и есть кривая
// сложности: первые десять ходов игрок учится уходить в сторону, дальше он
// считает линию атаки.
//
// Финиша нет: забег кончается, когда короля поймали или когда ходить стало
// некуда. Счёт это пережитые ходы, поэтому рекорд и уровень режима считаются с
// одного числа: каждые RACE_MOVES_PER_LEVEL ходов режим поднимает уровень.
// Уровень не влияет на поле: все играют на одном, иначе рекорды были бы
// несопоставимы.
//
// Здесь только таблица напряжённости. Правила живут в `modes.ts`
// (`player: 'king'`, `motion: 'greedy'`, `goal: 'survive'`, `scroll: true`),
// приток и сдвиг ряда - в `rules.ts`.

import type { PieceType } from './types';

/** Поле одинаковое у всех забегов: восемь колонок и двенадцать рядов. */
export const RACE_WIDTH = 8;
export const RACE_ROWS = 12;
/** Ряд старта короля: один ряд под ним остаётся, чтобы было куда отступить. */
export const RACE_KING_ROW = 1;
/** Сколько фигур стоит на поле до первого хода. */
export const RACE_PREFILL = 3;
/** Приток занимает столько верхних рядов: в один ряд фигуры встали бы стеной. */
export const RACE_SPAWN_ROWS = 2;
/** Сколько колонок держит приток на первой волне. */
export const RACE_SPAWN_MIN_WIDTH = 3;
/**
 * Сколько пережитых ходов поднимает уровень режима. Число взято из замера
 * жадного бота: забег на бегущем поле живёт десятки ходов, и один забег должен
 * давать два-три уровня, а не один и не десять.
 */
export const RACE_MOVES_PER_LEVEL = 12;
/**
 * Сколько пережитых ходов поднимает ВОЛНУ: ширину притока, его частоту и такт
 * поля. Это отдельные часы от уровня режима, и они идут вдвое быстрее:
 * RACE_MOVES_PER_LEVEL нужен, чтобы рекорды были сопоставимы, а игрок должен
 * увидеть рост сложности за один забег, а не за три. При шаге в восемь ходов
 * полоса притока проходит путь 3, 4, 5, 6, 7, 8 колонки за сорок ходов, то есть
 * весь рост виден за один обычный забег: жадный бот по замеру живёт 35 ходов.
 */
export const RACE_TIER_MOVES = 8;

/**
 * Сколько колонок по центру держит приток на данной волне: 3 на первой, вся
 * ширина доски с шестой. Полоса считается по центру поля, поэтому на чётном
 * числе колонок она симметрична.
 */
export function raceSpawnWidth(tier: number): number {
  return Math.min(RACE_WIDTH, RACE_SPAWN_MIN_WIDTH + Math.max(0, tier - 1));
}

/** Сколько фигур приходит за такт на данном напряжении. */
export function raceSpawnPerTurn(tier: number): number {
  return tier <= 2 ? 1 : tier <= 5 ? 2 : tier <= 9 ? 3 : 4;
}

/**
 * Раз в сколько ходов приходит такт притока. Первые две волны идут редко:
 * забег не должен обрываться раньше, чем игрок разобрался со стартовой пробкой.
 */
export function raceSpawnEvery(tier: number): number {
  return tier <= 2 ? 4 : tier <= 4 ? 2 : 1;
}

/**
 * Раз в сколько ходов поле сдвигает на ряд. Такт поля отдельный от такта
 * притока: ряд может уходить и тогда, когда никто не приходит, иначе вниз
 * ничего не едет и поле забивается.
 */
export function raceScrollEvery(tier: number): number {
  return tier <= 1 ? 4 : tier <= 2 ? 3 : tier <= 4 ? 2 : 1;
}

/** Уровень режима по счёту забега: счёт и есть пережитые ходы. */
export function raceLevelForMoves(moves: number): number {
  return 1 + Math.floor(Math.max(0, moves) / RACE_MOVES_PER_LEVEL);
}

/**
 * Волна по пережитым ходам: по ней считаются ширина притока, частота притока и
 * такт поля. Отдельно от уровня режима они идут потому, что уровень ждёт
 * рекорда, а волна обязана успевать менять игру здесь же.
 */
export function raceTierForMoves(moves: number): number {
  return 1 + Math.floor(Math.max(0, moves) / RACE_TIER_MOVES);
}

/**
 * Кем пополняется поле. Пешек здесь нет намеренно: они идут по одному ряду и
 * до короля доходят на десятом ходу, то есть только занимают клетки. Конь и
 * слон создают уклонения, ладья и ферзь прижимают линию.
 */
export function raceSpawnPool(tier: number): PieceType[] {
  if (tier <= 1) return ['rook', 'bishop', 'knight'];
  if (tier <= 3) return ['rook', 'rook', 'bishop', 'knight', 'knight'];
  if (tier <= 6) return ['rook', 'bishop', 'knight', 'knight', 'queen'];
  return ['rook', 'rook', 'bishop', 'knight', 'knight', 'queen', 'queen'];
}

/** Награда за забег: платим за дистанцию, потому что победы в режиме нет. */
export function raceCoinReward(moves: number): number {
  const level = raceLevelForMoves(moves);
  return Math.min(50, 5 + level + Math.floor(moves / 4));
}
