// «Гонки»: король против фигур, которые приходят сверху.
//
// Игрок - король: один шаг в любую из восьми сторон, взятие так же и в любую
// сторону тоже, назад включительно. Фигуры появляются в верхних рядах поля и
// дальше ходят по своим шахматным правилам, наступая на короля. Кто встал
// королю на клетку, тот его и снял.
//
// Финиша нет: забег кончается, когда короля поймали или когда ходить стало
// некуда. Счёт это пережитые ходы, поэтому рекорд и уровень режима считаются
// с одного числа: каждые RACE_MOVES_PER_LEVEL ходов режим поднимает уровень, а
// приток ускоряется (`tier`). Уровень не влияет на поле: все играют на одном,
// иначе рекорды были бы несопоставимы.
//
// Здесь только таблица напряжённости. Правила живут в `modes.ts`
// (`player: 'king'`, `motion: 'greedy'`, `goal: 'survive'`), приток - в `rules.ts`.

import type { PieceType } from './types';

/** Поле одинаковое у всех забегов: восемь колонок и двенадцать рядов. */
export const RACE_WIDTH = 8;
export const RACE_ROWS = 12;
/** Ряд старта короля: один ряд под ним остаётся, чтобы было куда отступить. */
export const RACE_KING_ROW = 1;
/** Сколько фигур стоит на поле до первого хода. */
export const RACE_PREFILL = 3;
/** Приток занимает столько верхних рядов: в один ряд фигуры встали бы стеной. */
export const RACE_SPAWN_ROWS = 2;
/**
 * Сколько пережитых ходов поднимает уровень режима. Число взято из замера:
 * жадный бот живёт 27-29 ходов, поэтому один забег обычно даёт два-три уровня,
 * а не один и не десять.
 */
export const RACE_MOVES_PER_LEVEL = 12;

/** Сколько фигур приходит за такт на данном напряжении. */
export function raceSpawnPerTurn(tier: number): number {
  return tier <= 2 ? 1 : tier <= 5 ? 2 : tier <= 9 ? 3 : 4;
}

/**
 * Раз в сколько ходов приходит такт притока. Первые две волны идут редко:
 * забег не должен обрываться раньше, чем игрок разобрался со стартовой пробкой,
 * поэтому минимум по замерам держится не на правиле, а на этом такте.
 */
export function raceSpawnEvery(tier: number): number {
  return tier <= 2 ? 4 : tier <= 4 ? 2 : 1;
}

/** Уровень режима по счёту забега: счёт и есть пережитые ходы. */
export function raceLevelForMoves(moves: number): number {
  return 1 + Math.floor(Math.max(0, moves) / RACE_MOVES_PER_LEVEL);
}

/**
 * Кем пополняется поле. Пешек здесь нет намеренно: они идут по одному ряду и
 * до короля доходят на десятом ходу, то есть только занимают клетки. Конь и
 * слон создают уклонения, ладья и ферзь прижимают линию.
 */
export function raceSpawnPool(tier: number): PieceType[] {
  if (tier <= 1) return ['rook', 'bishop', 'knight'];
  if (tier <= 3) return ['rook', 'rook', 'bishop', 'knight', 'knight'];
  if (tier <= 6) return ['rook', 'bishop', 'knight', 'knight', 'queen'];
  return ['rook', 'rook', 'bishop', 'knight', 'knight', 'queen', 'queen'];
}

/** Награда за забег: платим за дистанцию, потому что победы в режиме нет. */
export function raceCoinReward(moves: number): number {
  const level = raceLevelForMoves(moves);
  return Math.min(50, 5 + level + Math.floor(moves / 4));
}
